/**
 * Get profile by ID or name
 */
export function getCompanyProfile(
  companyIdOrName: string,
  targetRole: string = 'Software Developer'
): CompanyProfile {
  if (!companyIdOrName) {
    return POPULAR_COMPANY_PROFILES[0];
  }

  const clean = companyIdOrName.trim().toLowerCase();
  const found = POPULAR_COMPANY_PROFILES.find(
    (p) => p.id === clean || p.name.toLowerCase() === clean
  );

  if (found) {
    return found;
  }

  return createCustomCompanyProfile(companyIdOrName, targetRole);
}

